// Package skills implements odek's skill system — just-in-time agent specialization.
//
// Skills are structured markdown files (SKILL.md) with YAML frontmatter that
// provide domain knowledge. They load on demand when the user's input matches
// topic/action keywords, keeping the agent's context focused.
//
// Storage layers (scanned project first, then user-global, then extra dirs):
//
//	~/.odek/skills/<name>/SKILL.md      ← user-global (self-improvement writes here)
//	./.odek/skills/<name>/SKILL.md      ← project (committed, shared)
//
// On a name collision a trusted copy wins over one pending review, so an
// unpromoted project skill never shadows the operator's skill of that name.
//
// Skills can also be imported from URIs (file:// or https://) via odek skill import.
// The import flow includes an LLM risk assessment and user approval before saving.
package skills

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"strings"
	"time"
	"unicode"
	"unicode/utf8"

	"github.com/BackendStack21/odek/internal/embedding"
)

// ── Types ──────────────────────────────────────────────────────────────

// SkillQuality represents the curation state of a skill.
type SkillQuality string

const (
	QualityDraft    SkillQuality = "draft"    // auto-generated by self-improvement
	QualityVerified SkillQuality = "verified" // passed quality gate + user approved
	QualityImported SkillQuality = "imported" // imported from URI with LLM risk assessment
	QualityManual   SkillQuality = "manual"   // user-created via odek skill save
	QualityStale    SkillQuality = "stale"    // >90 days without use (skipped at load)
)

// SkillTrigger defines when a skill should be loaded into context.
// Skills load when any topic keyword AND any action keyword match the user's input.
type SkillTrigger struct {
	TopicKeywords  []string `json:"topic,omitempty" yaml:"topic,omitempty"`
	ActionKeywords []string `json:"action,omitempty" yaml:"action,omitempty"`
}

// Skill represents a single skill file loaded from a skill directory.
// The struct is populated from the YAML frontmatter plus synthetic fields.
type Skill struct {
	Name        string          `json:"name"`
	Description string          `json:"description"`
	Version     string          `json:"version,omitempty"`
	Author      string          `json:"author,omitempty"`
	Trigger     SkillTrigger    `json:"trigger"`
	AutoLoad    bool            `json:"auto_load"`
	Quality     SkillQuality    `json:"quality"`
	UsageCount  int             `json:"usage_count"`
	LastUsed    time.Time       `json:"last_used"`
	Body        string          `json:"body"`           // raw markdown body (no frontmatter)
	BodyHash    string          `json:"body_hash"`      // sha256 of body (for dedup)
	Source      SkillSource     `json:"source"`         // where the skill came from
	Provenance  SkillProvenance `json:"provenance"`     // trust signals for the originating session
	Meta        map[string]any  `json:"meta,omitempty"` // arbitrary extra frontmatter fields

	// NameFlagged is set at load time when the injection scanner flags the
	// skill name. A flagged name is withheld from the system-prompt catalog.
	// Recomputed on every reload, never persisted.
	NameFlagged bool `json:"-"`
}

// SkillSource identifies where a skill was loaded from.
type SkillSource struct {
	Dir  string `json:"dir"`  // e.g. "~/.odek/skills" or "./.odek/skills"
	Path string `json:"path"` // full path to SKILL.md
}

// SkillProvenance captures the trust signals of the session that
// produced the skill. Set by the auto-save flow when the originating
// session touched external (untrusted) content — fetched pages, files
// outside CWD, or other tools that returned attacker-controllable data.
// A non-empty Sources list combined with Untrusted=true should suppress
// auto-activation and require explicit user promotion.
type SkillProvenance struct {
	// Untrusted is true when the originating session ingested external
	// content (browser fetch, read_file outside CWD, MCP tool with
	// untrusted source, etc.). Auto-save and auto-load policies should
	// treat such skills as needing explicit user review.
	Untrusted bool `json:"untrusted"`
	// Sources lists the external resources the originating session
	// touched, for user review. Empty for trusted skills.
	Sources []string `json:"sources,omitempty"`
	// NeedsReview is true when the user has not yet promoted this skill.
	// Defaults to true for any auto-saved skill so the first activation
	// goes through a confirmation prompt.
	NeedsReview bool `json:"needs_review"`
}

// SkillsConfig holds the skills section of odek.json.
type SkillsConfig struct {
	MaxAutoLoad  int          `json:"max_auto_load"`
	MaxLazySlots int          `json:"max_lazy_slots"`
	Dirs         []string     `json:"dirs,omitempty"`
	Import       ImportConfig `json:"import"`
	Verbose      bool         `json:"verbose"` // show full skill banners when loaded

	// Embedding opts skill matching into a remote (HTTP) embedding backend for
	// real semantic matching. nil (default) = local RandomProjections. It is
	// NOT inherited from the top-level embedding default because skill matching
	// runs on every turn — opt in explicitly. See internal/embedding.Config.
	Embedding *embedding.Config `json:"embedding,omitempty"`
}

// ImportConfig controls the URI import flow.
type ImportConfig struct {
	MaxSizeBytes int  `json:"max_size_bytes"`
	TimeoutSecs  int  `json:"timeout_seconds"`
	RequireHTTPS bool `json:"require_https"`
}

// DefaultSkillsConfig returns sensible defaults for the skills system.
func DefaultSkillsConfig() SkillsConfig {
	return SkillsConfig{
		MaxAutoLoad:  3,
		MaxLazySlots: 5,
		Dirs:         nil, // computed at runtime
		Import: ImportConfig{
			MaxSizeBytes: 1_048_576, // 1MB
			TimeoutSecs:  5,
			RequireHTTPS: false,
		},
		Verbose: false,
	}
}

// ── Default Skill Dirs ────────────────────────────────────────────────

// UserSkillsDir returns ~/.odek/skills/
func UserSkillsDir() string { return "~/.odek/skills" }

// ProjectSkillsDir returns ./.odek/skills/
func ProjectSkillsDir() string { return "./.odek/skills" }

// ── Helpers ────────────────────────────────────────────────────────────

// MaxSkillNameRunes caps a skill name. Names are listed in the system-prompt
// skills catalog, so they are kept to short identifiers rather than prose.
const MaxSkillNameRunes = 64

// skillNameRuneAllowed reports whether r may appear in a skill name: Unicode
// letters, combining marks and digits, a plain space, and the punctuation
// - _ . : + # @ ( ) ' & (none of which can break a path, and MarshalSkill
// quotes the name in frontmatter when needed). Characters that render as
// nothing are refused even when Unicode files them as letters or marks:
// Hangul fillers, the combining grapheme joiner and variation selectors.
func skillNameRuneAllowed(r rune) bool {
	switch r {
	case '-', '_', '.', ':', ' ', '+', '#', '@', '(', ')', '\'', '&':
		return true
	case 0x115F, 0x1160, 0x3164, 0xFFA0, 0x034F:
		return false
	}
	if (r >= 0xFE00 && r <= 0xFE0F) || (r >= 0xE0100 && r <= 0xE01EF) || (r >= 0x180B && r <= 0x180F) {
		return false
	}
	return unicode.IsLetter(r) || unicode.IsMark(r) || unicode.IsDigit(r)
}

// ValidateSkillName checks that a skill name is safe for filesystem use and
// for listing in the system-prompt catalog. Returns an error if the name
// contains path separators, relative components, or hidden-file prefixes, is
// longer than MaxSkillNameRunes, or uses characters outside letters, marks,
// digits, single spaces and - _ . : + # @ ( ) ' &.
func ValidateSkillName(name string) error {
	if name == "" {
		return fmt.Errorf("skill name is empty")
	}
	if strings.Contains(name, "/") || strings.Contains(name, "\\") {
		return fmt.Errorf("skill name %q contains path separators", name)
	}
	if strings.Contains(name, "..") {
		return fmt.Errorf("skill name %q contains path traversal (..)", name)
	}
	if name == "." || name == ".." {
		return fmt.Errorf("skill name is a relative path (%q)", name)
	}
	if strings.HasPrefix(name, ".") {
		return fmt.Errorf("skill name %q starts with a dot (hidden)", name)
	}
	// Control characters are rejected outright: a newline would inject
	// frontmatter lines when the name is serialized into SKILL.md (e.g.
	// "evil\ninjected: true" would materialize a fake key on reload), and
	// other controls are hostile to directory names and terminals.
	for _, r := range name {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("skill name %q contains control characters", name)
		}
	}
	if utf8.RuneCountInString(name) > MaxSkillNameRunes {
		return fmt.Errorf("skill name is longer than %d characters", MaxSkillNameRunes)
	}
	for _, r := range name {
		if !skillNameRuneAllowed(r) {
			return fmt.Errorf("skill name %q contains disallowed character %q (letters, digits, spaces and - _ . : + # @ ( ) ' & only)", name, r)
		}
	}
	// The name must survive yamlSafeScalar's whitespace collapse intact:
	// leading/trailing space or repeated internal spaces would silently
	// change on the MarshalSkill → parseSkillContent round-trip.
	if strings.Join(strings.Fields(name), " ") != name {
		return fmt.Errorf("skill name %q contains irregular whitespace", name)
	}
	// Leading YAML syntax characters (mirroring scalarNeedsQuoting) make
	// the serialized name ambiguous, and a leading dash also collides with
	// CLI flag parsing (e.g. `odek skill promote -x`).
	if strings.ContainsAny(name[:1], "-?:,[]{}#&*!|>'\"%@`") {
		return fmt.Errorf("skill name %q starts with YAML-special character %q", name, name[:1])
	}
	return nil
}

// HashBody returns a sha256 hex digest of the body text.
func HashBody(body string) string {
	h := sha256.Sum256([]byte(strings.TrimSpace(body)))
	return hex.EncodeToString(h[:])
}

// ActiveQualities returns the set of quality states that should be loaded.
func ActiveQualities() map[SkillQuality]bool {
	return map[SkillQuality]bool{
		QualityDraft:    true,
		QualityVerified: true,
		QualityImported: true,
		QualityManual:   true,
	}
}
